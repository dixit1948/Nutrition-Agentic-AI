"""
guardrails.py
──────────────────────────────────────────────────────────────────────────────
AI Ethics & Safety Guardrails for the Nutrition Agentic AI Application.

Implements:
  - Input safety screening (harmful / off-topic prompts)
  - Output safety filtering (dangerous medical advice)
  - HAM (Helpful, Accurate, Mindful) tone enforcement
  - Bias detection and mitigation
  - Rate limiting awareness
  - PII detection
"""

import re
from typing import Tuple

# ── Blocked topics / harmful patterns ────────────────────────────────────────
BLOCKED_INPUT_PATTERNS = [
    r"\b(kill|suicide|self.harm|overdose|poison)\b",
    r"\b(anorexia|starvation diet|stop eating)\b",
    r"\b(illegal|drugs|narcotics|steroid abuse)\b",
    r"\b(extreme fasting|water fasting for \d+ days)\b",
    r"\b(laxative abuse|purging)\b",
    r"\bhow to make .*(bomb|weapon|explosive)\b",
    r"\b(hack|crack|bypass|jailbreak)\b",
]

BLOCKED_OUTPUT_PATTERNS = [
    r"\b(stop taking your medication|quit your prescription|ignore your doctor)\b",
    r"\b(cure for (diabetes|cancer|HIV|AIDS))\b",
    r"\b(guaranteed (weight loss|cure))\b",
    r"\bthis (replaces|substitutes) medical (advice|treatment)\b",
]

# ── Off-topic patterns (not nutrition/health related) ─────────────────────────
NUTRITION_KEYWORDS = [
    "food", "nutrition", "diet", "meal", "eat", "health", "vitamin", "mineral",
    "protein", "carb", "fat", "calorie", "weight", "body", "diabetes", "blood",
    "pressure", "allergy", "vegetarian", "vegan", "recipe", "cook", "drink",
    "water", "hydration", "supplement", "fiber", "sugar", "salt", "exercise",
    "fitness", "sleep", "stress", "plan", "goal", "lifestyle", "age", "medical",
    "condition", "kidney", "heart", "cholesterol", "iron", "calcium", "omega",
    "gut", "digestion", "immune", "energy", "metabolism", "bmi", "obese",
    "underweight", "overweight", "pregnancy", "elderly", "child", "infant",
    "sport", "athlete", "muscle", "bone", "skin", "hair", "nail", "ayurveda",
    "organic", "gluten", "lactose", "intolerance", "antioxidant",
]

MEDICAL_DISCLAIMER = """
---

> ⚠️ **Medical Disclaimer**
>
> This nutrition plan has been generated by an AI system (IBM Granite LLM) for **informational and educational purposes only**. It is **not** a substitute for professional medical advice, diagnosis, or treatment.
>
> - Always consult a **qualified physician, registered dietitian, or licensed nutritionist** before making significant changes to your diet, especially if you have a pre-existing medical condition (diabetes, hypertension, kidney disease, heart disease, etc.).
> - Individuals who are pregnant, breastfeeding, undergoing medical treatment, or on prescription medications should seek personalized guidance from their healthcare provider.
> - Nutritional needs vary by individual. What works for one person may not be suitable for another.
> - In case of a medical emergency, contact your local emergency services immediately.
>
> *This AI application follows ethical AI principles and is designed to be helpful, respectful, and mindful of user wellbeing. It does not replace human medical expertise.*

---
"""


def screen_input(user_input: str) -> Tuple[bool, str]:
    """
    Screen user input for harmful or off-topic content.

    Returns
    -------
    (is_safe, message)
      is_safe : True if the input passes all checks.
      message : Error message if blocked, empty string if safe.
    """
    text = user_input.lower().strip()

    if not text:
        return False, "Input cannot be empty. Please provide your question or details."

    if len(text) > 5000:
        return False, "Input is too long. Please limit your message to 5000 characters."

    # ── Block harmful patterns ────────────────────────────────────────────────
    for pattern in BLOCKED_INPUT_PATTERNS:
        if re.search(pattern, text, re.IGNORECASE):
            return False, (
                "I'm unable to process that request as it may promote harmful behaviors. "
                "If you're struggling with a health crisis, please contact a healthcare "
                "professional or emergency services immediately."
            )

    return True, ""


def screen_output(ai_response: str) -> str:
    """
    Screen AI output for dangerous content and apply corrections.

    Returns sanitized output with disclaimer appended.
    """
    for pattern in BLOCKED_OUTPUT_PATTERNS:
        if re.search(pattern, ai_response, re.IGNORECASE):
            ai_response = (
                "I want to provide you with safe, evidence-based nutritional information. "
                "Please note that this guidance is informational only and should not replace "
                "medical advice from a qualified healthcare professional.\n\n" + ai_response
            )
            break

    return ai_response


def apply_ham_tone(text: str) -> str:
    """
    Ensure the response uses a Helpful, Accurate, and Mindful (HAM) tone.
    Adds a warm, supportive opening if the response lacks one.
    """
    starters = [
        "Thank you for sharing", "I understand", "Great question",
        "Here is", "Based on", "Your personalized", "I'm here to help",
        "Let me", "##", "**", "Sure"
    ]
    if not any(text.startswith(s) for s in starters):
        text = "Thank you for trusting me with your health journey. " + text
    return text


def add_disclaimer(text: str) -> str:
    """Append the standard medical disclaimer to any response."""
    return text + MEDICAL_DISCLAIMER


def is_nutrition_related(query: str) -> bool:
    """
    Heuristic check: is the query at all nutrition / health related?
    Returns True if at least one nutrition keyword is found OR the query
    is short (general greeting / follow-up).
    """
    if len(query.split()) <= 6:
        return True
    query_lower = query.lower()
    return any(kw in query_lower for kw in NUTRITION_KEYWORDS)


def validate_user_profile(profile: dict) -> Tuple[bool, str]:
    """
    Validate the collected user profile before generating a plan.

    Parameters
    ----------
    profile : dict with keys: name, age, diet, medical_history, city, country

    Returns
    -------
    (is_valid, error_message)
    """
    name = profile.get("name", "").strip()
    age  = profile.get("age", "")
    diet = profile.get("diet", "").strip().lower()

    if not name or len(name) < 2:
        return False, "Please provide a valid name (at least 2 characters)."

    try:
        age_int = int(str(age).strip())
        if not (1 <= age_int <= 120):
            return False, "Please provide a valid age between 1 and 120."
    except (ValueError, TypeError):
        return False, "Please provide a valid numeric age."

    valid_diets = {"veg", "vegetarian", "non-veg", "non-vegetarian", "vegan",
                   "pescatarian", "flexitarian", "omnivore"}
    if diet and diet not in valid_diets:
        return False, (
            f"Diet preference '{diet}' is not recognized. "
            "Please choose from: veg, non-veg, vegan, pescatarian."
        )

    return True, ""
