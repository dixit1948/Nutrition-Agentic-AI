"""
plan_saver.py
──────────────────────────────────────────────────────────────────────────────
Saves generated nutrition plans as Markdown (.md) files.
"""

import os
import re
from datetime import datetime

PLANS_DIR = "plans"


def save_plan_to_md(plan_text: str, profile: dict) -> str:
    """
    Save a nutrition plan to a Markdown file.

    Parameters
    ----------
    plan_text : The generated nutrition plan text (markdown).
    profile   : User profile dict for metadata.

    Returns
    -------
    Path of the saved file (str).
    """
    os.makedirs(PLANS_DIR, exist_ok=True)

    name    = profile.get("name", "User").strip()
    safe_name = re.sub(r"[^\w\-]", "_", name)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename  = f"{PLANS_DIR}/nutrition_plan_{safe_name}_{timestamp}.md"

    header = f"""# 🥗 Personalized Nutrition Plan
## Generated by NutriAI — Powered by IBM Granite LLM

**Date Generated:** {datetime.now().strftime("%B %d, %Y at %I:%M %p")}

---

### 👤 User Profile Summary

| Field            | Details                              |
|------------------|--------------------------------------|
| **Name**         | {profile.get("name", "N/A")}         |
| **Age**          | {profile.get("age", "N/A")} years    |
| **Diet**         | {profile.get("diet", "N/A").title()} |
| **Medical History** | {profile.get("medical_history", "None reported")} |
| **Location**     | {profile.get("city", "")}, {profile.get("country", "")} |
| **Health Goals** | {profile.get("goals", "Maintain healthy lifestyle")} |
| **Weight**       | {profile.get("weight", "Not provided")} kg |
| **Height**       | {profile.get("height", "Not provided")} cm |

---

"""

    full_content = header + plan_text

    with open(filename, "w", encoding="utf-8") as f:
        f.write(full_content)

    return filename


def list_saved_plans() -> list[dict]:
    """Return list of saved plan files with metadata."""
    if not os.path.exists(PLANS_DIR):
        return []

    plans = []
    for fname in sorted(os.listdir(PLANS_DIR), reverse=True):
        if fname.endswith(".md"):
            fpath = os.path.join(PLANS_DIR, fname)
            stat  = os.stat(fpath)
            plans.append({
                "filename": fname,
                "path": fpath,
                "size_kb": round(stat.st_size / 1024, 1),
                "modified": datetime.fromtimestamp(stat.st_mtime).strftime("%Y-%m-%d %H:%M"),
            })
    return plans


def read_plan(filename: str) -> str:
    """Read a saved plan file."""
    fpath = os.path.join(PLANS_DIR, filename)
    if not os.path.exists(fpath):
        return ""
    with open(fpath, "r", encoding="utf-8") as f:
        return f.read()
